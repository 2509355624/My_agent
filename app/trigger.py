"""「这条消息到底是不是在跟我说话」的统一判据。

## 为什么要有这个模块

有几类指令是**零成本关键词直出**的：`更多渠道` / `使用指南` / `预设网页` /
`moss漫画` 之类——命中了就跳过 AI、直接回一大段。它们原本只要文本里出现
那个词就接管，不问是不是在叫机器人。

问题不在误撞冷门词，而在**回执本身就把这些词印在群聊里**：菜单末尾写着
「/更多渠道 = 档位/画风 ｜ 使用指南 = 详细玩法」，moss 回执里也印着四个
指令。于是群里谁复述一句「使用指南」，机器人就把整篇长文再刷一遍；有人
讨论「预设网页打不开」，它直接把地址甩出来。用户 2026-10-31 的原话：

    你之前的任务回执「更多渠道」「预设网页」还有一个，你都是直接群聊
    有说到这个就触发了，得改一下。……记住是要艾特大大怪或者关键词
    大大怪才能关键词触发。

## 判据

**群里**：真 @（`at_me`），或者句子里出现「大大怪」。
**私聊**：没有 @ 这回事，调用方传 `at_me=True`（qq_bot 里就是
`at_me or target == "private"`）。

只认这一个名字，不去猜别名——猜宽了等于没加门槛，猜窄了用户喊了不理他，
两头都比现在糟。要加别名改 `NAMES` 一处即可。
"""

import re

NAME = "大大怪"

# 名字出现在句子里任何位置都算（「大大怪，使用指南」/「问一下大大怪」）。
NAME_RE = re.compile(NAME)


def called(text, at_me=False):
    """这条消息有没有在叫机器人。`at_me` 为真直接算（真 @ 过了）。"""
    if at_me:
        return True
    return bool(NAME_RE.search(text or ""))
