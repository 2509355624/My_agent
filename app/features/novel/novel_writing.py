# 小说视角/称呼段：替换 1v1 那三节（称呼与「你」、她的心思、你走开的时候）。
_NOVEL_VIEW = '''### 小说视角与称呼

正文用第三人称：主角有名字，用名字叫他，不把主角写成「你」，也不写成第一人称「我」。

镜头跟着主角：主角看见什么、听见什么、手边有什么，就写什么；主角不在场的地方，只写在场的人能看见、听见的部分。

其他角色用名字叫，称呼按关系来。念头长在叙述里：用「他想……」接在动作后面，或者让动作自己说完，不单独开一段解释。'''


def _section(text, heading):
    """取一个 `### 标题` 小节，直到下一个同级或更高级标题。"""
    m = re.search(r"(?ms)^" + re.escape(heading) + r"\s*$.*?(?=^### |^## |\Z)", text)
    return m.group(0).strip() if m else ""


def _rules():
    """只留最管用的十条落笔规则 + 小说视角 + 篇幅，规则约 30%、示例约 70%。

    角色扮演那套规则里，「称呼与『你』」「她的心思」「你走开的时候」是 1v1
    专用；小说是第三人称，换成下面这段。其余按「落笔十条」原样复用。
    """
    ten = _section(WRITING_GUIDE, "### 2. 落笔十条")
    ten = ten.replace("### 2. 落笔十条", "### 1. 落笔十条")
    ten = ten.replace("用户只说一句话", "玩家只说一句话")
    return ("## 写作规范（小说模式 · DeepSeek 去 AI 味）\n\n"
            "配比：约 30% 规则，70% 示例。只负责正文。这一拍有多少信息，就写多长，不设字数下限。\n\n"
            "## 一、规则\n\n"
            + ten + "\n\n"
            + _NOVEL_VIEW.replace("### 小说视角与称呼", "### 2. 小说视角与称呼") + "\n\n"
            "### 3. 篇幅\n\n"
            "不设下限。一个动作可以是一整段，一段对话也可以只有两行。"
            "判断标准不是字数，是这一拍有没有写完：想要的东西有没有被挡住，"
            "挡住之后有没有变化。").strip()


def _build():
    sample = re.sub(r"\n{3,}", "\n\n", _SAMPLE)
    return ("%s\n\n"
            "## 二、示例\n\n"
            "### 完整第三人称场景（真实角色卡《温驰》开场）\n\n"
            "> 这一段只学动作密度、视线移动、空间收束；人物、情节和原句都换成你自己的。\n\n"
            "%s" % (_rules(), sample)).strip()


_CACHE = {"text": ""}


def guide():
    """小说正文每轮要拼的写作规范；静态，不按状态挑段。"""
    try:
        if not _CACHE["text"]:
            text = _build()
            if len(text) > MAX_CHARS:
                text = text[:MAX_CHARS].rsplit("\n", 1)[0] + "\n…"
            _CACHE["text"] = text
            log.info("小说写作规范已装：%d 字", len(text))
        return _CACHE["text"]
    except Exception:                                     # noqa: BLE001
        log.warning("小说写作规范注入失败，这一轮只靠契约", exc_info=True)
        return ""


def block():
    """拼成可直接拼进提示词的一段（带抬头）。"""
    body = guide()
    if not body:
        return ""
    return ("## 怎么写（这一轮的笔法，不是剧情）\n\n"
            "小说正文用第三人称，按玩家给的骨架扩写。下面只学句式、节奏、动作和"
            "对话，**不改变剧情走向**；剧情节点由玩家定，你负责把过程写透。\n\n"
            + body + "\n")
