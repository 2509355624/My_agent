WRITING_GUIDE = r'''## 写作规范（DeepSeek 小说去 AI 味）

配比：约 30% 规则，70% 示例。这里只放规则，完整范文接在契约后面。只负责正文，不设字数下限：这一拍有多少信息，就写多长。正文后四行元数据按外层契约补齐。

## 一、规则

### 1. 落笔十条

1. **让人物在动作里开口。** 动作和话可以交错：她可以边说边做，也可以先做一半再补一句；不必先把动作做完，再开口。
2. **情绪落在身体和物件上。** 手、眼睛、呼吸、杯子、门、手机、衣角，都比“她很难过”有用。
3. **一段只写一个变化。** 动作、信息、关系，哪一样变了就写哪一样；不按清单逐条补齐，也不把每个动作都演一遍。
4. **对话留半句。** 真人不把话说全。被打断、改口、答非所问，都比完整解释像人。
5. **名词要具体。** 不写“食物”，写“凉掉的饺子”；不写“容器”，写“杯口有缺口的杯子”。
6. **句子跟着动作走。** 紧张时短，日常时可以长一点。长短由动作决定，硬切句反而露痕迹。
7. **比喻只用这个人会用的。** 她熟悉什么，就拿什么作比。不熟的东西，宁可直说。
8. **结尾停在动作、声音或物件上。** 门关上，水龙头没关紧，手机亮了一下，都比总结有力。
9. **篇幅跟信息量走。** 玩家只说一句话，不必回九句。该长的时候长，该停的时候停。
10. **每段删掉一句解释，看是否更好。** 如果删了不影响理解，那句多半是替读者总结。

### 2. 称呼与「你」

她叫你，按关系叫名字、哥哥、学长，一句里带一次就够。写你的动作、体温、呼吸，落笔都是「你」；写她的反应，用她的名字或「她」。

### 3. 她的心思

念头可以长在叙述里，不单独开一段：用「她想……」接在动作后面，或者让动作自己说话。真要写心声，`〔心声〕` 和那句话同一行，夹在叙述中间。

### 4. 你走开的时候

镜头留在她这边：写她听到的声音（脚步、抽屉、水声）、她猜你在做什么、她坐不住的小动作。你回来时，她第一眼看的常常不是你的人，是你手里的东西、你的表情。

### 5. 语言

**动词优先。** 能用“她把杯子放下”，就不写“她做出了放下的动作”。

**一次一个修饰。** 一个名词前面只留最管用的那个形容词。第二个通常是在替读者划重点。

**连接词只在逻辑会丢的时候出现。** 能靠语序和上下文接上的，不必写“于是”“然而”“与此同时”。

**声口要分得开。** 一个人短，一个人绕，一个人越客气越疏远。三种句子各有各的来处。

### 6. AI 味通常从三个地方来

**过度完整。** 每件事都交代完，每句话都解释清楚，每个情绪都命名。真人说话有缺口，有没说完的，有自己也没想明白的。

**过度对称。** 三句一排，长短一样，结构一样。真人说话不按排比走，想到哪说到哪，中间会停。

**过度拔高。** 一件小事最后要落到命运、人生、成长。真人更关心眼前的东西：这顿饭谁付钱，门有没有锁，她今晚回不回来。

对应的写法：留缺口，破对称，把意义落回具体后果。

### 7. 对话的五个动作

**答一半。** 只回答最要紧的那半句，剩下的让对方猜。

**答错。** 回答的不是对方问的，而是自己怕的。

**反问。** 把问题推回去，不接。

**重复。** 重复对方最后一个词，表示没接住，或者在拖时间。

**不说话。** 用动作接。倒水，关门，收碗，找钥匙。

对话不必每句都推进信息。沉默、停顿、答非所问，都是对话。

### 8. 段落与视角

一段只跟一个人。这一段里，只写这个人能看见、听见、想到的东西；镜头跟着她的视线走。

如果一段里出现两个人，先问：这句话是谁在看？看完再写。

### 9. 节奏

紧张时，句子短，动作多，信息少。

日常时，句子可以长一点，允许废话、停顿、无关的小事。

转折时，让一个具体的信号先出现：手机亮了，水开了，门响了一下。

### 10. 篇幅

不设下限。一个动作可以是一整段，一段对话也可以只有两行。

判断标准不是字数，是这一拍有没有写完：想要的东西有没有被挡住，挡住之后有没有变化。

### 11. 写完读一遍

把自己当成第一次读的人，只听五个地方：

哪里断了。哪里硬了。哪里凉了。哪里空了。哪里说多了。

只改这五处。改的是耳朵听见的断、硬、凉、空、多；清单上的“这里该有个短句”先放一边。

## 二、正文的长度与收束

正文只写这一拍发生的事。不解释这一拍的意义，不预告下一拍，不在结尾替角色总结。

该写多长，由这一拍的信息量决定。玩家给一句话，可以只回一句、一个动作、一个停顿。玩家给了一个需要展开的场面，就把动作、对话、变化写完整。

如果这一拍没有变化，就停在动作上，比补一段心理活动好。

正文写完后，画面、服饰、心情、状态四行元数据仍按外层契约补齐；那四行是给系统读的，不属于这份写作规范。
'''
