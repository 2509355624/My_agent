def build():
    turns = []
    r = 0
    for i, (name, zone, f1, f2, f3, f4) in enumerate(SPECIES):
        t = T[i % len(T)]
        ctx = dict(name=name, zone=zone, f1=f1, f2=f2, f3=f3, f4=f4,
                   ask1=ASK1[i % len(ASK1)],
                   ask1s=ASK1_SHORT[i % len(ASK1_SHORT)],
                   ask2=ASK2[i % len(ASK2)],
                   ask2s=ASK2_SHORT[i % len(ASK2_SHORT)])
        g1 = t["g1"].format(**ctx)
        if i == 0:
            # 关键锚点：200 轮后要能被"第一次讲解的动物"检索到，光有物种名不够，
            # 时序词必须落在文本里。
            g1 = ("欢迎来到海洋馆，今天是我们开馆的第一场讲解，也是我第一次带大家走这条线。"
                  "第一站就是" + zone + "。" + f1)
        turns.append({"r": r + 1, "role": "guide", "text": g1})
        r += 1
        turns.append({"r": r + 1, "role": "visitor",
                      "text": t["v1"].format(**ctx)})
        r += 1
        turns.append({"r": r + 1, "role": "guide", "text": t["g2"].format(**ctx)})
        r += 1
        turns.append({"r": r + 1, "role": "visitor",
                      "text": t["v2"].format(**ctx)})
        r += 1
        turns.append({"r": r + 1, "role": "guide", "text": t["g3"].format(**ctx)})
        r += 1
    return turns


